internal fun translateRussianExerciseTextToEnglish(text: String): String {
    val normalized = text.trim()
    exactSentenceTranslations[normalized]?.let { return it }

    var translated = normalized

    phraseReplacements.forEach { (source, target) ->
        translated = translated.replace(source, target)
    }

    translated = wordRegex.replace(translated) { match ->
        wordTranslations[match.value] ?: match.value
    }

    return translated
        .replace("  ", " ")
        .replace(" ,", ",")
        .replace(" .", ".")
        .replace(" ?", "?")
        .replace(" !", "!")
        .replace(" :", ":")
        .trim()
}

